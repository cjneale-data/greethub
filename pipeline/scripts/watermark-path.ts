// Regenerates src/layout/watermark-path.ts: "GreetHub preview" as an SVG path from fonts/Andika-Bold.ttf.
// The guest proof draws this path instead of SVG <text>, because a Vercel function has no system fonts and sharp then
// renders every letter as an empty box. Run: npx tsx scripts/watermark-path.ts
import { readFileSync, writeFileSync } from "node:fs";
import fontkit from "@pdf-lib/fontkit";

const TEXT = "GreetHub preview";
const SIZE = 34;
const font = fontkit.create(readFileSync(new URL("../fonts/Andika-Bold.ttf", import.meta.url)));
const s = SIZE / font.unitsPerEm;
const run = font.layout(TEXT);
let x = 0;
const parts: string[] = [];
run.glyphs.forEach((g, i) => {
  // Font units are y-up; SVG is y-down. Baseline at y = 0, so the path drops in where <text x y> used to sit.
  const d = g.path.scale(s, -s).translate(x, 0).toSVG();
  if (d) parts.push(d);
  x += run.positions[i].xAdvance * s;
});
const round = (d: string) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
writeFileSync(
  new URL("../src/layout/watermark-path.ts", import.meta.url),
  `// Generated by scripts/watermark-path.ts from fonts/Andika-Bold.ttf. Do not edit by hand.\n` +
    `/** "${TEXT}" at ${SIZE}px as an SVG path, baseline at y = 0. */\n` +
    `export const WATERMARK_PATH = ${JSON.stringify(round(parts.join("")))};\n` +
    `export const WATERMARK_WIDTH = ${Math.round(x)};\n`,
);
console.log(`ok: ${Math.round(x)}px wide`);
